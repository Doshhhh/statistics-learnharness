const tables: Record<Locale, Record<MessageKey, string>> = { en, ru };
let current: Locale = "en";

export function resolveLocale(preference: LocalePreference | undefined, systemLanguage?: string): Locale {
  if (preference === "ru" || preference === "en") return preference;
  // The primary interface language only: it matches the language LearnHarness itself shows.
  const language = (systemLanguage ?? globalThis.navigator?.language ?? "en").toLowerCase();
  return language.startsWith("ru") ? "ru" : "en";
}

export function setLocale(locale: Locale): void {
  current = locale;
}

export function locale(): Locale {
  return current;
}

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  const template = tables[current][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (Object.hasOwn(vars, name) ? String(vars[name]) : match));
}

/** "47 min" / "6 h 05 min" in the active locale. */
export function duration(ms: number): string {
  const minutes = Math.round(ms / 60000);
  if (minutes < 60) return t("time.min", { n: minutes });
  return t("time.h", { h: Math.floor(minutes / 60), m: String(minutes % 60).padStart(2, "0") });
}
